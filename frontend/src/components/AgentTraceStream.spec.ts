import { createSSRApp, h } from 'vue'
import { renderToString } from '@vue/server-renderer'
import { describe, expect, it } from 'vitest'

import AgentTraceStream from '@/components/AgentTraceStream.vue'
import { cancelledFixture, errorFixture, normalFixture } from '@/components/__fixtures__/agentTrace.fixture'
import { i18n, setI18nLocale } from '@/i18n'
import type { AgentTraceEvent } from '@/types/agentTrace'

describe('AgentTraceStream', () => {
  it.each([
    ['completed', normalFixture],
    ['cancelled', cancelledFixture],
    ['failed', errorFixture],
  ] as const)('collapses Skills and tool calls together for a %s run', async (_, fixture) => {
    setI18nLocale('zh')
    const events: AgentTraceEvent[] = [
      {
        type: 'system_notice',
        task_id: 'fixture-task',
        seq: -1,
        timestamp: 0,
        kind: 'required_skill_loaded',
        name: 'humanizer-zh',
        load_method: 'server_prompt',
      },
      {
        type: 'system_notice',
        task_id: 'fixture-task',
        seq: 0,
        timestamp: 0,
        kind: 'raven_route',
        executor: 'antigravity_cli',
        provider: 'raven-yinhe',
        model: 'raven-yinhe/yinhe-thinking',
      },
      ...fixture.map((event) => event.type === 'run_start' ? {
        ...event,
        available_skills: ['humanizer-zh', 'catalog-only-skill'],
      } : event),
    ]
    const app = createSSRApp({ render: () => h(AgentTraceStream, { events }) })
    app.use(i18n)

    const html = await renderToString(app)
    const metadata = html.split('<button')[0]
    expect(metadata).toContain('yinhe-thinking')
    expect(metadata).not.toContain('Antigravity CLI')
    expect(metadata).not.toContain('raven-yinhe')
    expect(metadata).not.toContain('→')
    expect(metadata).toContain('已加载 Skills')
    expect(metadata).toContain('humanizer-zh')
    expect(html).toContain('aria-expanded="false"')
    expect(html).toContain('可用 Skills 2')
    expect(html).not.toContain('catalog-only-skill')
    expect(html).not.toContain('agent-trace__available-skills')
    expect(html).not.toContain('trace-card')
    expect(html).not.toContain('Generated by AI and can make mistakes')
  })

  it('shows only the last actual model after a route change', async () => {
    const events: AgentTraceEvent[] = [
      { type: 'system_notice', task_id: 'fixture-task', seq: -2, timestamp: 0,
        kind: 'raven_route', executor: 'claude_sdk', provider: 'first', model: 'first/previous-model' },
      { type: 'system_notice', task_id: 'fixture-task', seq: -1, timestamp: 1,
        kind: 'raven_route', provider: 'raven-yinhe', model: 'raven-yinhe/yinhe-thinking' },
      ...normalFixture,
    ]
    const app = createSSRApp({ render: () => h(AgentTraceStream, { events }) })
    app.use(i18n)
    const html = await renderToString(app)
    expect(html).toContain('yinhe-thinking')
    expect(html).not.toContain('previous-model')
    expect(html).not.toContain('Claude Agent SDK')
    expect(html).not.toContain('raven-yinhe')
  })

  it('shows a completed trace without adding an empty Skills section', async () => {
    setI18nLocale('en')
    const app = createSSRApp({ render: () => h(AgentTraceStream, { events: normalFixture }) })
    app.use(i18n)

    const html = await renderToString(app)
    expect(html).toContain('aria-expanded="false"')
    expect(html).toContain('2 tool calls')
    expect(html).not.toContain('Available Skills')
    expect(html).not.toContain('Loaded Skills')
  })

  it('keeps the full available Skill catalog collapsed by default', async () => {
    setI18nLocale('zh')
    const events: AgentTraceEvent[] = [
      {
        type: 'run_start',
        task_id: 'task-1',
        seq: 1,
        timestamp: 1,
        available_skills: [
          'ka-phased-array-antenna',
          'payload-management-unit',
          'tcpt027-db-modify',
        ],
        loaded_skills: ['ka-phased-array-antenna'],
      },
      {
        type: 'step_start',
        task_id: 'task-1',
        seq: 2,
        timestamp: 2,
        step_id: 'skill-1',
        tool_name: 'Skill',
        tool_input: { skill: 'ka-phased-array-antenna' },
      },
    ]
    const app = createSSRApp({
      render: () => h(AgentTraceStream, { events, running: true }),
    })
    app.use(i18n)

    const html = await renderToString(app)
    const detailsTag = html.match(/<details[^>]*agent-trace__available-skills[^>]*>/)?.[0]
    const availableSection = html.match(/<details[^>]*>[\s\S]*?<\/details>/)?.[0] || ''
    const loadedSection = html.match(
      /<div class="agent-trace__skills"[^>]*>[\s\S]*?<\/div>/,
    )?.[0] || ''

    expect(detailsTag).toBeTruthy()
    expect(detailsTag).not.toMatch(/\sopen(?:=|\s|>)/)
    expect(html).toContain('可用 Skills')
    expect(html).toMatch(/agent-trace__available-count"[^>]*>3<\/span>/)
    expect(html).toContain('已加载 Skills')
    expect(availableSection).toContain('ka-phased-array-antenna')
    expect(availableSection).toContain('payload-management-unit')
    expect(availableSection).toContain('tcpt027-db-modify')
    expect(loadedSection).toContain('ka-phased-array-antenna')
    expect(loadedSection).not.toContain('payload-management-unit')
    expect(loadedSection).not.toContain('tcpt027-db-modify')
  })
})
